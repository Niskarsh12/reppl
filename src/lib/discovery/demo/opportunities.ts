import type { OpportunityKind } from "../types";

/**
 * Fictional partners, written to be plausible but not real. Every name, handle,
 * reach figure and rate is illustrative — nothing here is a verified, bookable
 * creator. `evidence` marks how grounded the record is (all demo records are
 * "illustrative"). `homeCity` pins a physical partner to one city; unpinned
 * partners read as local wherever the brand asks (they take the requested
 * city, they don't claim to exist there).
 */
export interface DemoOpportunity {
  id: string;
  kind: OpportunityKind;
  name: string;
  detail: string;
  reach?: number;
  reachUnit?: string;
  scenes: string[];
  rate: { min: number; max: number };
  /** Illustrative (demo) | estimated (modelled) | verified (quoted). Defaults to illustrative in this catalogue. */
  evidence?: "illustrative" | "estimated" | "verified";
  /** Pins a physical venue/event to one real-feeling city; undefined means "takes the requested city". */
  homeCity?: string;
  formats: string[];
  about: string;
}

